import { readFile, appendFile } from "node:fs/promises";
import { nexsiStatus, companyStatus } from "../src/lib/nexsi-quality.ts";
import { companyBrief, guidanceCoverage } from "../src/lib/nexsi-brief.ts";
import { companyNewsCoverage } from '../src/lib/company-news.ts';
import { applyReviewedFacts, selectDisclosureEvents } from './lib/nexsi-disclosures.mjs';
import { REVIEWED_DISCLOSURES, REVIEWED_TEXT_DISCLOSURES } from './lib/nexsi-reviewed-disclosures.mjs';

const file = JSON.parse(await readFile("public/data/nexsi.json", "utf8"));
const now = Date.now(), blocked = file.companies.filter(c => companyStatus(c, now));
const problems = [...file.failures, ...blocked.map(c => `${c.symbol}: ${companyStatus(c, now)}`)];
const reviewedUrls = new Set([...Object.values(REVIEWED_DISCLOSURES), ...Object.values(REVIEWED_TEXT_DISCLOSURES)].map(review => review.url));
const reviewedDocuments = [...new Map(file.companies.flatMap(company => selectDisclosureEvents(company, now)
  .flatMap(event => (event.summary?.documents ?? []).filter(doc => reviewedUrls.has(doc.url))
    .map(doc => [doc.url, { symbol: company.symbol, doc, summary: event.summary }])))).values()];
const runStarted = Date.parse(process.env.REFRESH_STARTED_AT ?? file.generated);
const verifiedReviews = reviewedDocuments.filter(({ doc, summary }) => {
  const expected = applyReviewedFacts([], doc);
  return !summary.issue && Date.parse(doc.retrievedAt ?? '') >= runStarted && expected.length > 0
    && expected.every(fact => summary.facts.some(published => published.sourceUrl === doc.url && published.method === 'reviewed' && published.text === fact.text));
});
for (const item of reviewedDocuments.filter(item => !verifiedReviews.includes(item))) problems.push(`${item.symbol}: reviewed disclosure not freshly verified in this run: ${item.doc.url}`);
const status = nexsiStatus(file, now);
if (status) problems.push(status);
if (process.env.REFRESH_STARTED_AT && Date.parse(file.generated) < Date.parse(process.env.REFRESH_STARTED_AT)) problems.push("NexSI was not regenerated by this workflow run");
const sndk = file.companies.find(c => c.symbol === "SNDK");
const included = file.companies.filter(c => c.included && c.moves[1]);
const briefs = included.map(c => ({ symbol: c.symbol, ...companyBrief(c, c.moves[1], now) }));
const coverage = ['earnings', 'guidance', 'company-news'].map(category => {
  const covered = briefs.filter(b => b.categories.find(g => g.category === category)?.items.length);
  const missing = briefs.filter(b => !b.categories.find(g => g.category === category)?.items.length).map(b => b.symbol);
  return `${category}: ${covered.length}/${included.length} AI/technology securities with a source-backed ${category==='guidance'?'coverage assessment (not necessarily a financial forecast)':'summary'} for the latest move${missing.length ? `; not extracted: ${missing.join(', ')}` : ''}.`;
});
const guidanceGroups=[['AI/technology',briefs],['Full universe',file.companies.map(c=>({symbol:c.symbol,...companyBrief(c,c.moves[1]??{start:c.asOf,end:c.asOf},now)}))]].flatMap(([scope,rows])=>
  ['quantitative','limited','policy','not-issued','withdrawn','qualitative','missing'].map(status=>{
    const symbols=rows.filter(b=>guidanceCoverage(b.categories.find(g=>g.category==='guidance').items)===status).map(b=>b.symbol);
    return `${scope} guidance ${status}: ${symbols.length}${symbols.length ? ` (${symbols.join(', ')})` : ''}.`;
  }));
if (sndk && !sndk.issue && sndk.history.length >= 127 && !sndk.moves[1]) problems.push("SNDK daily attribution unavailable; review model coverage");
const lines = [
  `NexSI refresh: ${file.status}; generated ${file.generated}`,
  `${file.companies.length} securities; ${file.companies.filter(c => c.moves[1] && !companyStatus(c, now)).length} daily models; ${blocked.length} price-source issues; ${file.companies.filter(c => c.eventIssues.length).length} evidence-source issues.`,
  `Reviewed source rechecks: ${verifiedReviews.length}/${reviewedDocuments.length} referenced documents freshly retrieved, matched to reviewed source content and published with the reviewed facts.`,
  ...coverage,
  ...guidanceGroups,
  ...['missing','incomplete','confirmed','filings-only','reporting-only','none-found'].map(state=>{
    const symbols=file.companies.filter(c=>companyNewsCoverage(c,c.moves[1]??{start:c.asOf,end:c.asOf},now).status===state).map(c=>c.symbol);
    return `Full-universe company-news ${state}: ${symbols.length}${symbols.length?` (${symbols.join(', ')})`:''}.`;
  }),
  'Missing summaries are coverage gaps, not evidence of no announcement. Company news is limited to the nearby event window; earnings and guidance can include earlier background.',
  ...(sndk ? [`SNDK: ${sndk.asOf}, USD ${sndk.price}, ${sndk.provenance?.provider ?? "unknown source"}; 1-session return ${sndk.observedReturns[1]?.toFixed(4)}%; attribution ${sndk.moves[1] ? "available" : "withheld"}.`] : []),
  ...problems.map(p => `Review: ${p}`),
];
console.log(lines.join("\n"));
if (process.env.GITHUB_STEP_SUMMARY) await appendFile(process.env.GITHUB_STEP_SUMMARY, `### NexSI source verification\n\n${lines.join("\n\n")}\n`);
// Secondary enrichment warnings remain visible without blocking healthy core data.
if (problems.length || file.status !== "ok") console.log("::warning::NexSI has incomplete source coverage. Inspect the source verification summary and public health report.");
